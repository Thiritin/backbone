export type Action<A extends unknown[] = any[]> = (s: GameState, ...args: A) => ActionResult;
// An action and its arguments, for code that hands an action to the store without running it.
export type Call = [Action, ...unknown[]];
export type { LogEntry };
export const LOG_CAP = 50_000;

const modules = [games, deskInstall, addresses, lan, backups, bank, billing, bookkeeping, burnin, catalog, changes, checklist, clusters, community, datastores, company, console_, cpus, customers, dev, domains, holds, licence, licences, shoplink, vendorShop, oversell, packages, portal, firewall, horizont, quorum, replication, webpanel, docs, paperwork, tax, files, hardware, mail, mailServer, maintenance, market, marketing, media, moves, netsvcDns, netsvcMail, netsvcQuota, netsvcStorage, netsvcVpn, network, openveezee, os, orders, rates, registrar, remote, routers, sales, security, shop, snapshots, software, staff, start, store, suite, switches, support, desk, templates, travel, used, vms, vmwhere, vswitch, website];
const hyperModules = [haGroups, projects];
// Every exported function of 90-actions by its name, so a replay can call the actions a run logged.
export const ACTIONS: Record<string, Action> = Object.fromEntries([...modules, ...hyperModules].flatMap((m) => Object.entries(m).filter(([, f]) => typeof f === "function"))) as Record<string, Action>;
const NAMES = new Map<unknown, string>(Object.entries(ACTIONS).map(([k, f]) => [f, k]));

export const actionName = (fn: unknown): string | undefined => NAMES.get(fn);

// Runs a registered action with JSON copies of its arguments, the values a replay reads back, and logs it when it succeeds.
export function runAction(s: GameState, name: string, args: unknown[]): ActionResult {
  const fn = ACTIONS[name];
  if (!fn) throw new Error(`unknown action ${name}`);
  let n = args.length;
  while (n > 0 && args[n - 1] === undefined) n--;
  const json = JSON.stringify(args.slice(0, n));
  const r = fn(s, ...(JSON.parse(json) as unknown[]));
  if (r.ok && s.log.length < LOG_CAP) s.log.push({ hour: s.hour, minute: s.minute, name, args: JSON.parse(json) as unknown[] });
  return r;
}
