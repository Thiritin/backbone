// Builds src/ui/map/world-data.ts from Series of Tubes map files. The sources are parsed as text and never executed.
// Usage: node scripts/import-world.mjs <dir with 30-coastline.js, 40-city-coords.js, 50-cities.js, 60-cables.js>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/import-world.mjs <source dir>");
const src = (f) => readFileSync(join(dir, f), "utf8");
const literal = (text, name) => {
  const start = text.indexOf(`const ${name}=`);
  if (start < 0) throw new Error(`${name} not found`);
  const end = text.indexOf(";\n", start);
  return text.slice(text.indexOf("=", start) + 1, end);
};
const json = (s) => JSON.parse(s.replace(/,(\s*[\]}])/g, "$1"));
const r2 = (n) => Math.round(n * 100) / 100;

// Coastline: drop Antarctica and specks that vanish at world zoom.
const coast = json(literal(src("30-coastline.js"), "COAST_LL"))
  .filter((ring) => ring.length >= 4 && Math.max(...ring.map((p) => p[1])) > -58)
  .map((ring) => ring.map(([lon, lat]) => [r2(lon), r2(lat)]));

// Cities: coordinates by code, names and size from the city table.
const coords = json(literal(src("40-city-coords.js"), "CITY_LL"));
const names = {};
for (const m of src("50-cities.js").matchAll(/\{id:'(\w+)',name:'([^']+)'.*?P:(\d+)/g)) names[m[1]] = { name: m[2].replace(/\\'/g, "'"), p: +m[3] };
// Cities the game needs that Series of Tubes does not list: name -> [lon, lat].
const EXTRA = { Kerkrade: [6.07, 50.87], Nuremberg: [11.08, 49.45], Falkenstein: [12.37, 50.48] };
const tier = (p) => (p >= 900 ? 1 : p >= 200 ? 2 : 3);
const cities = Object.entries(coords).filter(([code]) => names[code]).map(([code, [lon, lat]]) => ({ code, name: names[code].name, lon: r2(lon), lat: r2(lat), tier: tier(names[code].p) }));
for (const [name, [lon, lat]] of Object.entries(EXTRA)) cities.push({ code: name.toLowerCase().slice(0, 3), name, lon, lat, tier: 2 });
const dcCities = [...readFileSync(new URL("../src/sim/20-world/datacenters.ts", import.meta.url), "utf8").matchAll(/^\s*\["[^"]+", "[^"]+", "[^"]+", "([^"]+)"/gm)].map((m) => m[1]);
const missing = [...new Set(dcCities)].filter((c) => !cities.some((x) => x.name === c));
if (missing.length) throw new Error(`datacenter cities without coordinates, add them to EXTRA: ${missing.join(", ")}`);

// Cables: blurbs call tr(), so they are blanked before parsing. Longitudes are unwrapped so a path never jumps across the dateline.
const cables = json(literal(src("60-cables.js"), "CABLES").replace(/tr\('[^']*'\)/g, "null")).map((c) => ({
  id: c.id,
  name: c.name,
  paths: c.pairs.map(([a, b, mid]) => {
    const pts = [coords[a], ...mid, coords[b]];
    if (pts.some((p) => !p)) throw new Error(`cable ${c.id}: unknown city ${a} or ${b}`);
    let prev = pts[0][0];
    return pts.map(([lon, lat]) => {
      lon += 360 * Math.round((prev - lon) / 360);
      prev = lon;
      return [r2(lon), r2(lat)];
    });
  }),
}));

const out = `// Map data from Series of Tubes (MIT, github.com/fjaeckel/seriesoftubes) and Natural Earth (public domain); generated by scripts/import-world.mjs.
export interface City { code: string; name: string; lon: number; lat: number; tier: 1 | 2 | 3 }
export interface Cable { id: string; name: string; paths: [number, number][][] }
export const COAST: [number, number][][] = ${JSON.stringify(coast)};
export const CITIES: City[] = ${JSON.stringify(cities)};
export const CABLES: Cable[] = ${JSON.stringify(cables)};
`;
writeFileSync(new URL("../src/ui/map/world-data.ts", import.meta.url), out);
console.log(`world-data.ts: ${coast.length} rings, ${cities.length} cities, ${cables.length} cables, ${(out.length / 1024).toFixed(0)} KB`);
