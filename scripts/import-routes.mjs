// Builds src/ui/map/roads.ts and routes.ts.
// Usage: node scripts/import-routes.mjs roads <dir with ne_10m_roads.shp/.dbf>   (Natural Earth roads, parsed as bytes, never executed)
//        node scripts/import-routes.mjs routes                                    (queries the OSRM demo server, resumable via routes-cache.json next to this script's output)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const [mode, dir] = process.argv.slice(2);
const MAX_POINTS = 80;
const ROADS_KB = 240;
const cities = JSON.parse(readFileSync(new URL("../src/ui/map/world-data.ts", import.meta.url), "utf8").match(/export const CITIES: City\[\] = (.*);\n/)[1]);
const r3 = (n) => Math.round(n * 1000) / 1000;

// Douglas-Peucker, iterative.
const simplify = (pts, tol) => {
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const t = len ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len)) : 0;
      const d = Math.hypot(px - ax - t * dx, py - ay - t * dy);
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
};

if (mode === "roads") {
  const shp = readFileSync(join(dir, "ne_10m_roads.shp"));
  const dbf = readFileSync(join(dir, "ne_10m_roads.dbf"));
  // dbf: header gives record count, header size, record size; field list gives column offsets.
  const n = dbf.readUInt32LE(4), hdr = dbf.readUInt16LE(8), rec = dbf.readUInt16LE(10);
  let off = 1, typeCol;
  for (let p = 32; dbf[p] !== 0x0d; p += 32) {
    const name = dbf.toString("latin1", p, p + 11).replace(/\0.*/, ""), size = dbf[p + 16];
    if (name === "type") typeCol = [off, size];
    off += size;
  }
  const types = [];
  for (let i = 0; i < n; i++) types.push(dbf.toString("latin1", hdr + i * rec + typeCol[0], hdr + i * rec + typeCol[0] + typeCol[1]).trim());
  // shp: records follow a 100 byte header; polylines (type 3) hold parts and points.
  const lines = [];
  for (let p = 100, i = 0; p < shp.length; i++) {
    const clen = shp.readUInt32BE(p + 4) * 2, b = p + 8;
    p = b + clen;
    if (shp.readInt32LE(b) !== 3 || types[i] !== "Major Highway") continue;
    const np = shp.readInt32LE(b + 36), npt = shp.readInt32LE(b + 40);
    const parts = [...Array(np)].map((_, k) => shp.readInt32LE(b + 44 + 4 * k)).concat(npt);
    const pt = (k) => [shp.readDoubleLE(b + 44 + 4 * np + 16 * k), shp.readDoubleLE(b + 44 + 4 * np + 16 * k + 8)];
    for (let k = 0; k < np; k++) lines.push([...Array(parts[k + 1] - parts[k])].map((_, j) => pt(parts[k] + j)));
  }
  let tol = 0.02, out;
  for (;; tol *= 1.25) {
    const roads = lines.map((l) => simplify(l, tol).map(([x, y]) => [r3(x), r3(y)])).filter((l) => l.length >= 2 && Math.hypot(l[0][0] - l.at(-1)[0], l[0][1] - l.at(-1)[1]) > tol * 4 || l.length > 2);
    out = `// Major roads from Natural Earth (public domain); generated by scripts/import-routes.mjs.\nexport const ROADS: [number, number][][] = ${JSON.stringify(roads)};\n`;
    if (out.length < ROADS_KB * 1024) { console.log(`roads.ts: ${roads.length} lines of ${lines.length}, tol ${tol.toFixed(3)}, ${(out.length / 1024).toFixed(0)} KB`); break; }
  }
  writeFileSync(new URL("../src/ui/map/roads.ts", import.meta.url), out);
} else if (mode === "routes") {
  const cachePath = new URL("../../routes-cache.json", import.meta.url); // two levels up from scripts/: outside the repo
  const cache = existsSync(cachePath) ? JSON.parse(readFileSync(cachePath, "utf8")) : {};
  const km = (a, b) => { const r = Math.PI / 180; return 6371 * Math.hypot((b.lon - a.lon) * r * Math.cos(((a.lat + b.lat) / 2) * r), (b.lat - a.lat) * r); };
  // Trips only run between datacenter cities and the basement city.
  const dcSrc = readFileSync(new URL("../src/sim/20-world/datacenters.ts", import.meta.url), "utf8");
  const names = new Set([...dcSrc.matchAll(/^\s*\["[^"]+", "[^"]+", "[^"]+", "([^"]+)"/gm)].map((m) => m[1]));
  for (const m of dcSrc.matchAll(/\{ id: "[^"]+", name: "[^"]+", city: "([^"]+)"/g)) names.add(m[1]);
  const used = cities.filter((c) => names.has(c.name));
  const pairs = [];
  for (const a of used) for (const b of used) if (a.code < b.code) pairs.push([a, b]);
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const near = (p, c) => Math.abs(p[0] - c.lon) <= 0.5 && Math.abs(p[1] - c.lat) <= 0.5;
  let done = 0;
  for (const [a, b] of pairs) {
    const key = `${a.code}-${b.code}`;
    if (key in cache) continue;
    let line = null;
    for (let attempt = 0; attempt < 3; attempt++) {
      await sleep(300);
      try {
        const res = await fetch(`https://router.project-osrm.org/route/v1/driving/${a.lon},${a.lat};${b.lon},${b.lat}?overview=full&geometries=geojson`);
        const j = await res.json();
        if (j.code === "Ok") line = j.routes[0].geometry.coordinates;
        if (res.ok || j.code === "NoRoute") break;
      } catch {}
    }
    if (line) {
      let tol = 0.005, s = line;
      while (s.length > MAX_POINTS) s = simplify(line, (tol *= 1.3));
      line = s.map(([x, y]) => [r3(x), r3(y)]);
      if (!near(line[0], a) || !near(line.at(-1), b)) line = null; // snapped to a distant road
    }
    cache[key] = line;
    if (++done % 100 === 0) { writeFileSync(cachePath, JSON.stringify(cache)); console.log(`${done}/${pairs.length - Object.keys(cache).length + done}`); }
  }
  writeFileSync(cachePath, JSON.stringify(cache));
  const keys = new Set(pairs.map(([a, b]) => `${a.code}-${b.code}`));
  const fit = (l) => { let tol = 0.005, s = l; while (s.length > MAX_POINTS) s = simplify(l, (tol *= 1.3)); return s; };
  const routes = Object.fromEntries(Object.entries(cache).filter(([k, v]) => v && keys.has(k)).map(([k, v]) => [k, fit(v)]).sort(([x], [y]) => (x < y ? -1 : 1)));
  const out = `// Driving routes between game cities from the OSRM demo server (OpenStreetMap data, ODbL); generated by scripts/import-routes.mjs.\nexport const ROUTES: Record<string, [number, number][]> = ${JSON.stringify(routes)};\n`;
  writeFileSync(new URL("../src/ui/map/routes.ts", import.meta.url), out);
  console.log(`routes.ts: ${Object.keys(routes).length} routes, ${pairs.length - Object.keys(routes).length} missing, ${(out.length / 1024).toFixed(0)} KB`);
} else throw new Error("usage: import-routes.mjs roads <dir> | routes");
