// Builds src/ui/map/world-geo.ts (borders, rivers, lakes, country label points) from Natural Earth 1:50m (public domain).
// Usage: node scripts/import-geo.mjs <dir with ne_50m_* files saved as admin_0_boundary_lines_land.json, admin_1_states_provinces_lines.json, rivers_lake_centerlines.json, lakes.json, admin_0_countries.json>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/import-geo.mjs <source dir>");
const feats = (f) => JSON.parse(readFileSync(join(dir, f), "utf8")).features;
const r2 = (n) => Math.round(n * 100) / 100;

const simplify = (pts, tol) => {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const t = len ? Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len)) : 0;
      const d = Math.hypot(px - ax - t * dx, py - ay - t * dy);
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
};
const clean = (l, tol) => simplify(l, tol).map(([x, y]) => [r2(x), r2(y)]);
const lines = (g) => (g.type === "LineString" ? [g.coordinates] : g.type === "MultiLineString" ? g.coordinates : []);
const rings = (g) => (g.type === "Polygon" ? [g.coordinates[0]] : g.type === "MultiPolygon" ? g.coordinates.map((p) => p[0]) : []);

const borders = feats("admin_0_boundary_lines_land.json").flatMap((f) => lines(f.geometry)).map((l) => clean(l, 0.02));
const regions = feats("admin_1_states_provinces_lines.json").filter((f) => !f.properties.FEATURECLA?.includes("Disputed")).flatMap((f) => lines(f.geometry)).map((l) => clean(l, 0.04));
const rivers = feats("rivers_lake_centerlines.json").filter((f) => f.properties.scalerank <= 6).flatMap((f) => lines(f.geometry)).map((l) => clean(l, 0.03));
const lakes = feats("lakes.json").flatMap((f) => rings(f.geometry)).map((l) => clean(l, 0.03)).filter((l) => l.length >= 4);
const countries = feats("admin_0_countries.json")
  .filter((f) => f.properties.LABELRANK <= 5 && f.properties.ISO_A2_EH?.length === 2)
  .map((f) => [f.properties.ISO_A2_EH, r2(f.properties.LABEL_X), r2(f.properties.LABEL_Y), f.properties.LABELRANK]);

const j = (v) => JSON.stringify(v);
writeFileSync(new URL("../src/ui/map/world-geo.ts", import.meta.url), `// Borders, rivers, lakes and country label points from Natural Earth (public domain); generated by scripts/import-geo.mjs.
type Line = [number, number][];
export const BORDERS: Line[] = ${j(borders)};
export const REGION_LINES: Line[] = ${j(regions)};
export const RIVERS: Line[] = ${j(rivers)};
export const LAKES: Line[] = ${j(lakes)};
// ISO 3166 alpha-2, lon, lat, label rank (1 = shown first).
export const COUNTRIES: [string, number, number, number][] = ${j(countries)};
`);
console.log({ borders: borders.length, regions: regions.length, rivers: rivers.length, lakes: lakes.length, countries: countries.length });
